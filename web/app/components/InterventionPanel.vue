<script setup lang="ts">
import { computed } from 'vue'
import type { MultimodalStore } from '../composables/useMultimodal'
import { formatDuration } from '../utils/format'

const props = defineProps<{ store: MultimodalStore }>()

const {
  categoryIsIntervention,
  selectedCategory,
  interventionRows,
  interventionLoading,
  interventionError,
  interventionCategories,
  selectedOrigin,
} = props.store

const reachableCount = computed(() => interventionRows.value.filter((row) => row.reachable).length)

const groupedCount = computed(
  () => new Set(interventionRows.value.map((row) => row.islandId)).size,
)

const rowsByIsland = computed(() => {
  const map = new Map<string, typeof interventionRows.value>()
  for (const row of interventionRows.value) {
    const current = map.get(row.islandId) ?? []
    current.push(row)
    map.set(row.islandId, current)
  }
  return [...map.entries()].map(([islandId, rows]) => ({
    islandId,
    islandName: rows[0]?.islandName ?? islandId,
    atollName: rows[0]?.atollName ?? '',
    population: rows[0]?.population ?? 0,
    reachable: rows.some((row) => row.reachable),
    minutes: rows.find((row) => row.reachable)?.minutes ?? null,
    rows,
  }))
})
</script>

<template>
  <section class="mm-panel mm-panel--wide mm-interventions" aria-labelledby="mm-interventions-title">
    <header class="mm-panel__head">
      <div>
        <p class="mm-eyebrow">Intervention coverage</p>
        <h2 id="mm-interventions-title" class="mm-panel__title">
          {{ selectedCategory?.label ?? 'Selected category' }}
        </h2>
      </div>
      <span v-if="categoryIsIntervention" class="mm-tag mm-tag--accent">
        {{ reachableCount }} of {{ interventionRows.length }} reachable
      </span>
      <span v-else class="mm-tag">Facility category</span>
    </header>

    <template v-if="!categoryIsIntervention">
      <p class="mm-panel__note">
        The selected destination category is a <strong>facility</strong> category. Intervention
        coverage appears when the destination category is built from facility service evidence
        (for example <code>service:dialysis</code> or <code>service:dental</code>).
      </p>
      <details v-if="interventionCategories.length" class="mm-panel__note">
        <summary>
          {{ interventionCategories.length }} intervention categories are published — choose one
          in <strong>Destination category</strong> to see its island coverage.
        </summary>
        <p class="mm-interventions__categories">
          <span v-for="definition in interventionCategories" :key="definition.id" class="mm-chip">
            {{ definition.label }} ({{ definition.facilityCount }})
          </span>
        </p>
      </details>
      <p v-else class="mm-panel__note">
        No intervention categories are published yet. The service-evidence layer is generated by
        the data pipeline; this panel stays honest rather than inferring services from a facility
        name.
      </p>
    </template>

    <template v-else>
      <p class="mm-panel__note">
        Facilities claiming this intervention, grouped by island. Reachability is
        <strong>{{ selectedOrigin?.name ?? 'the selected origin' }} → island</strong> under the
        current network and scenario; it is physical network access at island level, not a
        confirmation that the service is open, staffed or bookable.
      </p>

      <p v-if="interventionLoading" class="mm-loading-inline" role="status">
        <span class="mm-spinner mm-spinner--small" aria-hidden="true" /> Checking
        {{ interventionCategories.length ? 'intervention' : 'facility' }} islands…
      </p>
      <p v-else-if="interventionError" class="mm-alert mm-alert--warn" role="alert">
        {{ interventionError }}
      </p>

      <div v-else-if="rowsByIsland.length" class="mm-interventions__summary">
        <span><strong>{{ interventionRows.length }}</strong> facility claims</span>
        <span><strong>{{ groupedCount }}</strong> islands</span>
        <span><strong>{{ reachableCount }}</strong> reachable by network</span>
      </div>

      <div v-if="!interventionLoading && !interventionError && rowsByIsland.length" class="mm-interventions__list">
        <article
          v-for="group in rowsByIsland"
          :key="group.islandId"
          class="mm-intervention"
          :class="{ 'mm-intervention--unreachable': !group.reachable }"
        >
          <div class="mm-intervention__head">
            <h3 class="mm-intervention__island">{{ group.islandName }}</h3>
            <span class="mm-chip">{{ group.atollName }}</span>
            <span class="mm-chip">{{ group.population }} residents</span>
            <span v-if="group.reachable" class="mm-tag mm-tag--good">
              Reachable · {{ group.minutes !== null ? formatDuration(group.minutes) : '—' }}
            </span>
            <span v-else class="mm-tag mm-tag--muted">Not reachable on this run</span>
          </div>
          <ul class="mm-intervention__facilities">
            <li v-for="row in group.rows" :key="row.facilityId" class="mm-intervention__facility">
              <span class="mm-intervention__name">{{ row.facilityName }}</span>
              <span class="mm-intervention__meta">
                <span class="mm-chip">{{ row.confidence }}</span>
                <span v-if="row.sourceDate" class="mm-chip">source {{ row.sourceDate }}</span>
                <span v-if="row.userAdded" class="mm-chip mm-chip--accent">user-added</span>
              </span>
              <span v-if="row.detail" class="mm-intervention__detail">{{ row.detail }}</span>
            </li>
          </ul>
        </article>
      </div>

      <p v-if="!interventionLoading && !interventionError && !rowsByIsland.length" class="mm-panel__note">
        No facility claims this intervention in the prepared network. That is a data-coverage
        statement, not evidence that the service is unavailable anywhere.
      </p>
    </template>
  </section>
</template>
